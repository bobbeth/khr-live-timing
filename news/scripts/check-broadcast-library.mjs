import fs from 'node:fs/promises';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const read=async path=>JSON.parse(await fs.readFile(new URL(path,import.meta.url),'utf8'));
const historical=(await read('../../archive/index.json')).events;
const live=(await read('../data/live/index.json')).events;
const entries=[...new Map([...historical,...live].map(e=>[e.subsession_id,e])).values()];
const index=await read('../data/broadcasts.json');
const nodes=new Map();
const node=id=>{if(!nodes.has(id))nodes.set(id,{innerHTML:'',textContent:''});return nodes.get(id);};
const app=node('app'),location={hash:'#broadcasts'};
const esc=v=>String(v??'').replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
const context={window:{},location,document:{getElementById:node},fetch:async()=>({ok:true,json:async()=>index})};
vm.createContext(context);
vm.runInContext(await fs.readFile(new URL('../assets/broadcasts.js',import.meta.url),'utf8'),context);
const lib=context.window.createMMTVBroadcastLibrary({app,entries:()=>entries,seasonName:e=>e.competition||'Fall Fest 2026',esc,fmtDay:d=>d});
const videos=lib.build(index,entries);
const validMappings=entries.filter(e=>/^[A-Za-z0-9_-]{11}$/.test(index.events[e.subsession_id]?.video_id||''));
assert.equal(videos.length,new Set(validMappings.map(e=>index.events[e.subsession_id].video_id)).size);
assert.equal(videos.flatMap(v=>v.races).length,validMappings.length);
assert.equal(lib.build(index,[...entries,...entries]).length,videos.length);
assert.equal(videos.find(v=>v.id==='IyXQ4OjSR3Y').races.length,2);
assert.ok(videos.some(v=>v.inferred));
assert.throws(()=>lib.build({schema_version:'wrong'},entries));
const filters={season:'all',series:'Bomber Stocks',round:'6',search:'',order:'newest'};
assert.equal(videos.filter(v=>lib.matches(v,filters)).length,1);
const mismatched={races:[{entry:{series:'Bomber Stocks',round:1}},{entry:{series:'Cushion Kings',round:2}}]};
assert.equal(lib.matches(mismatched,{...filters,round:'2'}),false,'All selected filters must match one covered race');
await lib.library();
assert.equal((node('broadcast-grid').innerHTML.match(/class="broadcast-card"/g)||[]).length,videos.length);
assert.ok(!node('broadcast-grid').innerHTML.includes('<iframe'),'Library should not load 16 video players');
node('broadcast-series').onchange({target:{value:'Bomber Stocks'}});
node('broadcast-round').onchange({target:{value:'6'}});
assert.equal((node('broadcast-grid').innerHTML.match(/class="broadcast-card"/g)||[]).length,1);
assert.ok(node('broadcast-grid').innerHTML.includes('89810317'));
assert.ok(node('broadcast-grid').innerHTML.includes('89812470'));
node('broadcast-search').oninput({target:{value:'NONEXISTENT TRACK'}});
assert.ok(node('broadcast-grid').innerHTML.includes('No recordings match'));
for(const video of videos){
 location.hash='#broadcast/'+video.id;await lib.recording(video.id);
 assert.ok(app.innerHTML.includes('youtube-nocookie.com/embed/'+video.id));
 for(const r of video.races)assert.ok(app.innerHTML.includes('#race/'+r.entry.subsession_id));
 assert.equal((app.innerHTML.match(/<iframe/g)||[]).length,1);
 const saved=video.races.filter(r=>Number.isSafeInteger(r.link.start_seconds)&&r.link.start_seconds>0);
 assert.equal((app.innerHTML.match(/OPEN SAVED RACE START/g)||[]).length,saved.length);
}
location.hash='#broadcast/abcdefghijk';await lib.recording('abcdefghijk');assert.ok(app.innerHTML.includes('NOT FOUND'));
const broken=lib.build({...index,events:{...index.events,'89810317':{video_id:'<invalid>'}}},entries);
assert.equal(broken.flatMap(v=>v.races).length,validMappings.length-1);
const failingContext={window:{},location:{hash:'#broadcasts'},document:{getElementById:node},fetch:async()=>{throw Error('offline');}};
vm.createContext(failingContext);vm.runInContext(await fs.readFile(new URL('../assets/broadcasts.js',import.meta.url),'utf8'),failingContext);
const failing=failingContext.window.createMMTVBroadcastLibrary({app,entries:()=>entries,seasonName:()=>'',esc,fmtDay:d=>d});await failing.library();assert.ok(app.innerHTML.includes('TRY AGAIN'));
console.log(`PASS: ${videos.length} deduplicated recordings, ${validMappings.length} race links, filters, search, players, saved offsets, invalid IDs and fetch failure.`);
